// ---------- Apply translations ----------
function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  try { localStorage.setItem("icsc_lang", lang); } catch {}
  document.dispatchEvent(new CustomEvent("icsc:lang", { detail: lang }));
}

document.querySelectorAll(".lang-switch button").forEach(btn => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

// Restore saved language, else auto-detect from browser
(() => {
  let saved = null;
  try { saved = localStorage.getItem("icsc_lang"); } catch {}
  if (saved && I18N[saved]) return applyLang(saved);
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("es")) applyLang("es");
  else if (nav.startsWith("zh")) applyLang("zh");
  else applyLang("en");
})();

